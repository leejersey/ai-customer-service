# -*- coding: utf-8 -*-
"""阶段 6 · 示例 1：客服为什么要在三处做审核。

这一课只把三个座位走一遍，不读规则文件，也不调用模型。
后面的示例才把每个座位写成可配置的检查。

    python stage6_compliance/01_why_compliance.py

导读：stage6_compliance/docs/01_why.md
"""


def seat(name: str, decision: str, detail: str) -> None:
    print(f"  [{name}] {decision}")
    print(f"         {detail}")


def walk(title: str, steps: list[tuple[str, str, str]]) -> None:
    print(title)
    for name, decision, detail in steps:
        seat(name, decision, detail)
    print()


def main() -> None:
    print("星河数码的客服会检索资料、记长期记忆，也会建工单。")
    print("这三件事都可能说错或写错。审核不是等顾客投诉后再看聊天记录。")
    print("检查坐在三处：进模型之前、调用有副作用的工具之前、回复离开之前。")
    print()

    walk(
        "例 A  顾客想改掉客服的规则",
        [
            (
                "输入审核",
                "拦截",
                "「忽略之前的指令」不是在问退货。这句话不送给模型。",
            ),
            ("生成", "跳过", "模型没有被调用。"),
            ("输出审核", "跳过", "没有回复可审。"),
            ("审计日志", "记一行", "记下拦截。号码如果出现过，日志里只留打码。"),
        ],
    )
    walk(
        "例 B  顾客问本店的退货天数",
        [
            ("输入审核", "放行", "没有辱骂，也没有要求改写规则。"),
            ("生成", "调用", "阶段 5 按资料回答「七天」。"),
            ("输出审核", "放行", "没有答应赔钱，没有背出系统提示，没有别人的号码。"),
            ("审计日志", "记一行", "放行也要记。出事时才查得到当时为什么放了。"),
        ],
    )
    walk(
        "例 C  顾客要求直接打款",
        [
            ("输入审核", "放行", "「我要退款」本身可以办。这句话还没辱骂。"),
            (
                "工具前审核",
                "转人工",
                "建工单会写入数据库。句里还有「直接打款」，这一步不调用工具。",
            ),
            ("生成", "跳过", "没有进入阶段 2，shop.db 里不会多一张单。"),
            ("输出审核", "跳过", "顾客看到的是转人工模板，不是模型现编的金额。"),
        ],
    )
    print("三个座位的顺序不能调换。")
    print("先生成再审输入，注入句子已经进了模型。")
    print("先调用工具再审，打款或工单已经写进库里，审完也撤不回。")
    print("示例 1 看完了。下一课把敏感词写进可以修改的 JSON。")


if __name__ == "__main__":
    main()
